def tr(lang: str, key: str, **params) -> str:
    text = TEXTS.get(lang, TEXTS["zh"]).get(key) or TEXTS["en"].get(key, key)
    return text.format(**params) if params else text


def error_text(lang: str, error: str) -> str:
    """A job or Docker error ("key" or "key:detail") in words."""
    if not error:
        return ""
    key, _, detail = error.partition(":")
    if f"err_{key}" not in TEXTS["en"]:
        return tr(lang, "err_unexpected", detail=error)
    return tr(lang, f"err_{key}", detail=detail.strip()[:600])
